// Copies the path data of the icons we use from @phosphor-icons/core (MIT) into a typed module.
// Run after changing ICONS: node scripts/generate-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const ICONS = [
  'arrow-left',
  'arrow-right',
  'arrows-clockwise',
  'caret-down',
  'check',
  'check-circle',
  'clock',
  'copy',
  'crown',
  'desktop',
  'dice-five',
  'door-open',
  'hourglass-medium',
  'info',
  'link',
  'magnifying-glass',
  'minus',
  'moon',
  'play',
  'plus',
  'sign-in',
  'sign-out',
  'sun',
  'trash',
  'user',
  'users',
  'warning-circle',
  'x',
];

const require = createRequire(import.meta.url);
const entries = ICONS.map((name) => {
  const svg = readFileSync(
    require.resolve(`@phosphor-icons/core/assets/regular/${name}.svg`),
    'utf8',
  );
  const paths = [...svg.matchAll(/<path d="([^"]+)"\/>/g)];
  if (paths.length !== 1 || !svg.includes('viewBox="0 0 256 256"')) {
    throw new Error(`${name}: expected exactly one path in a 256x256 viewBox`);
  }
  return `  '${name}': '${paths[0][1]}',`;
});

writeFileSync(
  new URL('../src/app/ui/icon/icons.ts', import.meta.url),
  `// Generated by scripts/generate-icons.mjs from @phosphor-icons/core (regular weight, MIT).
// Do not edit by hand.

/** SVG path data for a 256x256 viewBox. */
export const ICONS = {
${entries.join('\n')}
} as const;

export type IconName = keyof typeof ICONS;
`,
);
console.log(`Generated ${ICONS.length} icons.`);
